    def load_gguf_and_parse_graph(self, model_path):
        print("\n[1/4] 解析 GGUF 计算图...")
        gf = gguf.GGUFReader(model_path)

        def get_val(key, default=0):
            try:
                if key in gf.fields:
                    field = gf.fields[key]
                    if hasattr(field, 'parts') and len(field.parts) > 0:
                        val = field.parts[0]
                        if hasattr(val, 'item'):
                            return val.item()
                        return int(val)
            except Exception as e:
                print(f"   ⚠️ 读取 {key} 失败: {e}")
            return default

        self.hp = {
            "n_layer":      get_val("llama.block_count", 28),
            "dim":          get_val("llama.embedding_length", 3584),
            "n_head":       get_val("llama.attention.head_count", 28),
            "n_kv_head":    get_val("llama.attention.head_count_kv", 4),
            "vocab_size":   get_val("llama.vocab_size", 152064),
            "ffn_dim":      get_val("llama.feed_forward_length", 18944),
            "dtype":        "float32",
        }
        self.hp["head_dim"] = self.hp["dim"] // max(1, self.hp["n_head"])

        self.tensor_names = [t.name for t in gf.tensors]
        self.build_llama_graph()
        print(f"✅ 解析完成 | layers={self.hp['n_layer']} | dim={self.hp['dim']} | heads={self.hp['n_head']} | KV={self.hp['n_kv_head']}")
