export SNAP="${SNAP:-$REPO_ROOT/models/gemma-4-26B-A4B-it-qat-4bit}"
export COLI_METRICS_ROOT="${COLI_METRICS_ROOT:-$REPO_ROOT/var/colibri_metrics_warm_local}"
export COLI_METAL_GEMMA4_MOE_BLOCK="${COLI_METAL_GEMMA4_MOE_BLOCK:-1}"
export COLI_METAL_GEMMA4_MOE_BLOCK_MAX_S="${COLI_METAL_GEMMA4_MOE_BLOCK_MAX_S:-32}"
export GEMMA4_EXPERT_PREFETCH="${GEMMA4_EXPERT_PREFETCH:-0}"
export GEMMA4_EXPERT_PREFETCH_DEPTH="${GEMMA4_EXPERT_PREFETCH_DEPTH:-1}"
export GEMMA4_EXPERT_W_ADOPT_BUDGET="${GEMMA4_EXPERT_W_ADOPT_BUDGET:-2}"
export GEMMA4_EXPERT_W_SLOT1_ADOPT_GAP="${GEMMA4_EXPERT_W_SLOT1_ADOPT_GAP:-1}"
export GEMMA4_EXPERT_W_SLOT1_PROTECT_ADOPT_WINDOW="${GEMMA4_EXPERT_W_SLOT1_PROTECT_ADOPT_WINDOW:-1}"
