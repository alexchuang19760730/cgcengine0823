export GEMMA4_EXPERT_DECODE_BOOTSTRAP_SYNC_LOAD="${GEMMA4_EXPERT_DECODE_BOOTSTRAP_SYNC_LOAD:-1}"

HOST="${HOST:-127.0.0.1}"
PORT="${PORT:-18080}"
MODEL_ID="${MODEL_ID:-gemma4-colibri-warm}"
ENGINE="${ENGINE:-$REPO_ROOT/colibri/c/gemma4}"
ARCH="${ARCH:-gemma4}"

exec python3 "$REPO_ROOT/colibri/c/openai_server.py" \
  --model "$SNAP" \
  --engine "$ENGINE" \
  --arch "$ARCH" \
  --host "$HOST" \
  --port "$PORT" \
  --model-id "$MODEL_ID"
